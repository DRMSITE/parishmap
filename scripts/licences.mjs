// Writes THIRD_PARTY_LICENSES.md from the packages that end up in the built site, and checks
// that each licence can be combined with AGPL-3.0-or-later.
//
//   node scripts/licences.mjs           write THIRD_PARTY_LICENSES.md
//   node scripts/licences.mjs --check   fail if a licence is unknown or not compatible, or if
//                                       the file is out of date (for CI)
//
// "Packages that end up in the site" means the lock file's non-development entries (the
// `dependencies` in package.json and what they need). Development tools are not distributed.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const root = resolve(import.meta.dirname, "..");

/** Licences that may be combined with AGPL-3.0-or-later and shipped in a built site. */
const COMPATIBLE = new Set([
  "MIT",
  "ISC",
  "BSD-2-Clause",
  "BSD-3-Clause",
  "Apache-2.0",
  "0BSD",
  "CC0-1.0",
  "CC-BY-4.0",
  "Unlicense",
  "BlueOak-1.0.0",
  "MPL-2.0",
  "Zlib",
  "Python-2.0",
]);

/**
 * True if every alternative in an SPDX expression we can read is compatible. An `OR` needs only
 * one compatible choice; an `AND` needs all.
 * @param {string} expression
 */
export function isCompatible(expression) {
  const text = expression.replace(/[()]/g, " ").trim();
  if (!text) return false;
  return text
    .split(/\s+OR\s+/i)
    .some((choice) =>
      choice.split(/\s+AND\s+/i).every((id) => COMPATIBLE.has(id.trim())),
    );
}

/**
 * Things in the site that are not npm packages.
 */
const OTHER = [
  {
    name: "Font Awesome Free icons (src/icons)",
    version: "7.3.0",
    licence: "CC-BY-4.0",
    note: "Copyright Fonticons, Inc. Each file keeps its own licence comment.",
  },
  {
    name: "OpenStreetMap data and tiles",
    version: "",
    licence: "ODbL-1.0",
    note: "Data © OpenStreetMap contributors; attribution is shown on the map.",
  },
];

/**
 * @param {Record<string, any>} lock The parsed package-lock.json.
 * @param {(path: string) => Record<string, any> | null} readPackage Reads a package.json by lock path.
 */
export function collect(lock, readPackage) {
  /** @type {{ name: string, version: string, licence: string }[]} */
  const out = [];
  for (const [path, entry] of Object.entries(lock.packages ?? {})) {
    if (!path || entry.dev || entry.devOptional) continue;
    const name = path.replace(/^.*node_modules\//, "");
    const meta = readPackage(path) ?? {};
    const licence =
      typeof meta.license === "string"
        ? meta.license
        : (meta.license?.type ?? entry.license ?? "UNKNOWN");
    out.push({ name, version: entry.version ?? meta.version ?? "", licence });
  }
  return out.sort((a, b) => a.name.localeCompare(b.name));
}

/** @param {{ name: string, version: string, licence: string }[]} packages */
export function render(packages) {
  const rows = packages
    .map((p) => `| ${p.name} | ${p.version} | ${p.licence} |`)
    .join("\n");
  const others = OTHER.map(
    (o) => `| ${o.name} | ${o.version} | ${o.licence} | ${o.note} |`,
  ).join("\n");
  return `# Third-party licences

ParishMap is licensed under the AGPL-3.0-or-later (see [LICENSE](LICENSE)). It includes the
software and data below, under their own licences. This file is generated by
\`node scripts/licences.mjs\`; do not edit it by hand.

## Packages in the built site

| Package | Version | Licence |
| --- | --- | --- |
${rows}

## Other material

| Material | Version | Licence | Note |
| --- | --- | --- | --- |
${others}

## Map tile providers

Tiles from OpenStreetMap, Ordnance Survey or any provider you configure are not part of this
software. Each has its own terms, and the council that uses them is responsible for following them
(see [docs/tile-providers.md](docs/tile-providers.md)).
`;
}

function main() {
  const lockPath = resolve(root, "package-lock.json");
  if (!existsSync(lockPath)) {
    console.error("There is no package-lock.json. Run `npm install` first.");
    process.exit(1);
  }
  const lock = JSON.parse(readFileSync(lockPath, "utf8"));
  const packages = collect(lock, (path) => {
    const file = resolve(root, path, "package.json");
    return existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : null;
  });

  const bad = packages.filter((p) => !isCompatible(p.licence));
  if (bad.length) {
    console.error("These licences are unknown or may not be compatible with the AGPL:");
    for (const p of bad) console.error(`  ${p.name}@${p.version}: ${p.licence}`);
    console.error("Check each by hand, then add it to COMPATIBLE in scripts/licences.mjs if it is.");
    process.exit(1);
  }

  const text = render(packages);
  const target = resolve(root, "THIRD_PARTY_LICENSES.md");
  if (process.argv.includes("--check")) {
    const current = existsSync(target) ? readFileSync(target, "utf8") : "";
    if (current.replace(/\r\n/g, "\n") !== text) {
      console.error("THIRD_PARTY_LICENSES.md is out of date. Run `npm run licences`.");
      process.exit(1);
    }
    console.log(`Licences checked: ${packages.length} packages, all compatible, file up to date.`);
    return;
  }
  writeFileSync(target, text);
  console.log(`Wrote THIRD_PARTY_LICENSES.md (${packages.length} packages).`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
